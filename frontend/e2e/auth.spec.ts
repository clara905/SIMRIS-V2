import { test, expect } from '@playwright/test'
test('masuk, keluar, serta pembatasan akses', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Masuk ke SIMRIS' })).toBeVisible()
  await page.getByLabel('Email', { exact: true }).fill('admin@simris.go.id')
  await page.getByLabel('Kata sandi', { exact: true }).fill('Simris123!')
  await page.getByRole('button', { name: 'Masuk ke ruang kerja' }).click()
  await expect(page.getByRole('navigation', { name: 'Navigasi utama' })).toBeVisible()
  await page.getByRole('button', { name: 'Keluar', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Ya, keluar' }).click()
  await expect(page).toHaveURL(/masuk/)
})
test('ganti password wajib', async ({ page }) => {
  await page.goto('/masuk')
  await page.getByLabel('Email', { exact: true }).fill('baru@simris.go.id')
  await page.getByLabel('Kata sandi', { exact: true }).fill('Simris123!')
  await page.getByRole('button', { name: 'Masuk ke ruang kerja' }).click()
  await expect(page).toHaveURL(/ganti-password/)
  await page.getByLabel('Kata sandi baru', { exact: true }).fill('KataSandiBaru123!')
  await page.getByLabel('Konfirmasi kata sandi baru').fill('KataSandiBaru123!')
  await page.getByRole('button', { name: 'Simpan kata sandi' }).click()
  await expect(page.getByRole('navigation', { name: 'Navigasi utama' })).toBeVisible()
  await page.getByRole('button', { name: 'Keluar', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Ya, keluar' }).click()
  await page.getByLabel('Email', { exact: true }).fill('baru@simris.go.id')
  await page.getByLabel('Kata sandi', { exact: true }).fill('KataSandiBaru123!')
  await page.getByRole('button', { name: 'Masuk ke ruang kerja' }).click()
  await expect(page.getByRole('navigation', { name: 'Navigasi utama' })).toBeVisible()
})
